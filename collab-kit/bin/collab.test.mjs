import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync, spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'video-collab-test-'));
const collab = path.join(fixture, '.ai-collab');
const bin = path.join(collab, 'bin/collab.mjs');
fs.mkdirSync(path.dirname(bin), {recursive:true});
fs.copyFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'collab.mjs'), bin);
const id='WO-20261107-001', dir=path.join(collab,'work-orders',id);
fs.mkdirSync(dir,{recursive:true});
const write=(name,value)=>fs.writeFileSync(path.join(dir,name),JSON.stringify(value));
const sha=name=>createHash('sha256').update(fs.readFileSync(path.join(dir,name))).digest('hex');
const run=(...args)=>execFileSync(process.execPath,[bin,...args],{cwd:fixture,encoding:'utf8'});
const fails=(...args)=>spawnSync(process.execPath,[bin,...args],{cwd:fixture,encoding:'utf8'}).status!==0;
try {
  write('order.json',{id,episode:'SERIES',stage:'setup',title:'fixture'});
  write('report-r1.json',{status:'done',summary:'tested output'});
  assert.match(run('status'),/待评审/);
  assert.ok(fails('closeout',id),'self-check alone must not close');
  write('user-decision-r1.json',{actor:'user',work_order_id:id,report_approvals:[{report_round:1,artifact_sha256:sha('report-r1.json'),verdict:'pass'}],query_resolutions:[]});
  assert.match(run('status'),/已完成.*收口批准:用户/);
  run('closeout',id);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'closeout-r1.json'))).approved_by,'user');
  assert.ok(fails('closeout',id),'existing receipt is never overwritten');
  write('report-r1.json',{status:'done',summary:'changed after approval'});
  assert.match(run('status'),/待评审/,'changed report invalidates user approval');
  write('review-r1.json',{verdict:'pass'});
  assert.match(run('status'),/已完成.*收口批准:Claude/,'Claude alone can approve');
  write('query-r1.json',{queries:[{id:'Q1'}]});
  assert.match(run('status'),/待裁决/,'unresolved query blocks closure');
  write('user-decision-r2.json',{actor:'user',work_order_id:id,report_approvals:[],query_resolutions:[{query_round:1,artifact_sha256:sha('query-r1.json'),query_ids:['Q1'],decision:'accept_codex'}]});
  assert.match(run('status'),/已完成.*收口批准:Claude/);
  write('query-r1.json',{queries:[{id:'Q1',question:'changed'}]});
  assert.match(run('status'),/待裁决/,'changed query invalidates prior decision');
  write('resolution-r1.json',{resolutions:[{query_id:'Q1',decision:'defer'}]});
  assert.match(run('status'),/待裁决/,'deferred query remains unresolved');
  write('resolution-r1.json',{resolutions:[{query_id:'Q1',decision:'accept_codex'}]});
  write('report-r2.json',{status:'done',summary:'next report'});
  assert.match(run('status'),/待评审/,'approval of r1 does not approve r2');
  write('review-r2.json',{verdict:'revise'});
  assert.match(run('status'),/待修改/);
  write('user-decision-r3.json',{actor:'user',work_order_id:id,report_approvals:[{report_round:2,artifact_sha256:sha('report-r2.json'),verdict:'pass'}],query_resolutions:[]});
  assert.match(run('status'),/已完成.*收口批准:用户/,'explicit user decision takes precedence');
  run('closeout',id);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'closeout-r2.json'))).approved_by_label,'用户');
  write('report-r3.json',{status:'done',summary:'Claude-only approval'});
  write('review-r3.json',{verdict:'pass'});
  run('closeout',id);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'closeout-r3.json'))).approved_by,'Claude');
  write('report-r4.json',{status:'partial',summary:'component only'});
  assert.match(run('status'),/部分完成/);
  write('user-decision-r4.json',{actor:'user',work_order_id:id,report_approvals:[{report_round:4,artifact_sha256:sha('report-r4.json'),verdict:'pass'}],query_resolutions:[]});
  assert.match(run('status'),/部分结果已批准，工单未完成/);
  assert.ok(fails('closeout',id),'approval of a partial report does not close the entire work order');
  console.log('PASS: approval required; either approver identified; immutable receipts; report/query hashes; defer/rework; new-round isolation.');
} finally {
  assert.equal(path.dirname(path.resolve(fixture)),path.resolve(os.tmpdir()));
  assert.ok(path.basename(fixture).startsWith('video-collab-test-'));
  fs.rmSync(fixture,{recursive:true,force:true});
}
